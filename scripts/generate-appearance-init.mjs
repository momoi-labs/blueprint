import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { appearanceDefaults, appearanceOptions, phoneKeys, presetDefaults } from '../apps/kiso-gallery/src/appearance-settings.ts';

const template = readFileSync(new URL('../apps/kiso-gallery/src/appearance-init.template.js', import.meta.url), 'utf8');
const output = new URL('../apps/kiso-gallery/public/appearance-init.js', import.meta.url);
const fields = JSON.stringify({ options: appearanceOptions, phoneKeys, defaults: appearanceDefaults, presetDefaults }, null, 2).replace(/\[([^\]]*)\]/g, (_, items) => `[${items.split(/,\s*/).map(item => item.trim()).join(', ')}]`).replace(/^/gm, '  ').trimStart();
const generated = template
  .replace('// Runs before styles', '// Generated by scripts/generate-appearance-init.mjs from src/appearance-settings.ts. Do not edit.\n// Runs before styles')
  .replace('__APPEARANCE_FIELDS__', fields);

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    console.error(`${fileURLToPath(output)} is out of date. Run: node scripts/generate-appearance-init.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(output, generated);
}
